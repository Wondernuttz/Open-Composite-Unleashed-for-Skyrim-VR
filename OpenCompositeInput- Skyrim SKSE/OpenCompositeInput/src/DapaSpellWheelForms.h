constexpr bool IsUiLocalId(std::uint32_t id) {
    return std::binary_search(localIds.begin(),localIds.end(),id);
}
class ResolvedForms {
    std::array<std::uint32_t,localIds.size()> ids{};
    std::size_t count=0;
public:
    void Add(std::uint32_t id) { if(id && count<ids.size())ids[count++]=id; }
    void Seal() { std::sort(ids.begin(),ids.begin()+count); }
    std::size_t Size() const { return count; }
    bool Matches(std::uint32_t id,bool projectile) const {
        return projectile && id && std::binary_search(ids.begin(),ids.begin()+count,id);
    }
};
